"use client";

import * as React from "react";
import { cn } from "@/lib/utils";

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, style, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-lg border bg-card text-card-foreground shadow-md hover-card",
      className
    )}
    style={{
      backgroundColor: 'var(--card-bg, white)',
      borderRadius: 'var(--radius, 0.85rem)',
      boxShadow: 'var(--card-shadow, 0 10px 25px -5px rgba(0, 0, 0, 0.08), 0 8px 10px -6px rgba(0, 0, 0, 0.03))',
      transition: 'transform 0.3s ease, box-shadow 0.3s ease, border-color 0.3s ease',
      ...style
    }}
    onMouseOver={(e) => {
      // Force apply hover effect
      e.currentTarget.style.transform = 'translateY(-4px)';
      e.currentTarget.style.boxShadow = '0 20px 25px -5px rgba(0, 0, 0, 0.1), 0 10px 10px -5px rgba(0, 0, 0, 0.04)';
      e.currentTarget.style.borderColor = '#3B82F6';
    }}
    onMouseOut={(e) => {
      // Remove hover effect
      e.currentTarget.style.transform = '';
      e.currentTarget.style.boxShadow = 'var(--card-shadow, 0 10px 25px -5px rgba(0, 0, 0, 0.08), 0 8px 10px -6px rgba(0, 0, 0, 0.03))';
      e.currentTarget.style.borderColor = '';
    }}
    {...props}
  />
));
Card.displayName = "Card";

